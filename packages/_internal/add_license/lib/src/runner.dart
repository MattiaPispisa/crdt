import 'dart:io';

import 'package:add_license/src/header.dart';
import 'package:add_license/src/license_info.dart';
import 'package:path/path.dart' as path;

/// Directory names a package's `.dart` file walk never descends into:
/// tool caches, build output, the SDK pin, non-Dart toolchains, and `gen`
/// folders of generated code (such as `flutter gen-l10n` output).
const _excludedDirs = {
  '.dart_tool',
  'build',
  '.fvm',
  '.git',
  'node_modules',
  '.dart_frog',
  'gen',
};

/// File names a package's `.dart` file walk skips: files generated by a
/// build step, never hand-written.
bool _isGenerated(String fileName) =>
    fileName == 'generated.dart' ||
    fileName.endsWith('.g.dart') ||
    fileName.endsWith('.freezed.dart') ||
    fileName.endsWith('.mocks.dart');

/// Every `.dart` file under [packageRoot], skipping [_excludedDirs] and
/// [_isGenerated] files.
///
/// Stops at a nested `pubspec.yaml`: that directory is a package of its
/// own (an `example/` or `flutter_example/` with its own `LICENSE`), run
/// through its own call instead of inheriting [packageRoot]'s.
List<File> dartFilesOf(Directory packageRoot) {
  final result = <File>[];

  void walk(Directory dir, {required bool isRoot}) {
    if (!isRoot && File(path.join(dir.path, 'pubspec.yaml')).existsSync()) {
      return;
    }
    for (final entity in dir.listSync(followLinks: false)) {
      final name = path.basename(entity.path);
      if (entity is Directory) {
        if (!_excludedDirs.contains(name)) {
          walk(entity, isRoot: false);
        }
      } else if (entity is File &&
          name.endsWith('.dart') &&
          !_isGenerated(name)) {
        result.add(entity);
      }
    }
  }

  walk(packageRoot, isRoot: true);
  return result..sort((a, b) => a.path.compareTo(b.path));
}

/// The outcome of [applyLicense] or [checkLicense] on a package.
class LicenseReport {
  /// Creates a report.
  const LicenseReport({required this.added, required this.missing});

  /// Files [applyLicense] stamped. Always empty from [checkLicense].
  final List<File> added;

  /// Files that have no header: every file, from [checkLicense]; none,
  /// from [applyLicense], which stamps them instead.
  final List<File> missing;

  /// Whether every file already had, or now has, a header.
  bool get isComplete => missing.isEmpty;
}

/// Stamps the SPDX header of [packageRoot]'s `LICENSE` on every `.dart`
/// file that does not already have one.
LicenseReport applyLicense(Directory packageRoot) {
  final info = readLicenseInfo(packageRoot);
  final added = <File>[];

  for (final file in dartFilesOf(packageRoot)) {
    final content = file.readAsStringSync();
    if (hasHeader(content)) {
      continue;
    }
    file.writeAsStringSync(applyHeader(content, info));
    added.add(file);
  }

  return LicenseReport(added: added, missing: const []);
}

/// Reports every `.dart` file of [packageRoot] missing the SPDX header,
/// without changing anything.
LicenseReport checkLicense(Directory packageRoot) {
  // Read the LICENSE to fail fast on a missing or unrecognized one, even
  // when every file already has a header.
  readLicenseInfo(packageRoot);

  final missing = <File>[
    for (final file in dartFilesOf(packageRoot))
      if (!hasHeader(file.readAsStringSync())) file,
  ];

  return LicenseReport(added: const [], missing: missing);
}
